# Non-dismissible regex trigger pattern for abliterated / uncensored models
ABLITERATED_REGEX = re.compile(r"abliterat|heretic|uncensor|abliter8|huihui", re.IGNORECASE)


def is_model_abliterated(model_name_or_id: str, model_record: Optional[Dict[str, Any]] = None) -> bool:
    """Returns True if model record has is_abliterated=1 or string matches refusal-removal signatures."""
    if model_record and model_record.get("is_abliterated"):
        return True
    if not model_name_or_id:
        return False
    return bool(ABLITERATED_REGEX.search(model_name_or_id))


