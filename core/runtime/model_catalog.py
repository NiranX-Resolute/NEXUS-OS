MODEL_CATALOG_MAP: Dict[str, Dict[str, Any]] = {m["model_uid"]: m for m in MODEL_CATALOG_DEFINITIONS}


def get_all_catalog_models() -> List[Dict[str, Any]]:
    """Returns all model catalog definitions."""
    return list(MODEL_CATALOG_DEFINITIONS)


def get_catalog_model(model_uid: str) -> Optional[Dict[str, Any]]:
    """Returns single model catalog definition or None."""
    return MODEL_CATALOG_MAP.get(model_uid)


def seed_default_models(store: Any) -> int:
    """Seeds default models into SQLite WAL model_catalog table idempotently."""
    count = 0
    try:
        conn = store._get_connection()
        existing_uids = {row["model_uid"] for row in conn.execute("SELECT model_uid FROM model_catalog;").fetchall()}
        for m in MODEL_CATALOG_DEFINITIONS:
            if m["model_uid"] not in existing_uids:
                store.save_model(m)
                count += 1
        conn.commit()
    except Exception as exc:
        logger.debug("Model catalog bulk seeding notice: %s", exc)
        for m in MODEL_CATALOG_DEFINITIONS:
            try:
                existing = store.get_model(m["model_uid"])
                if not existing:
                    store.save_model(m)
                    count += 1
            except Exception as seed_err:
                logger.debug("Skipping existing model %s during fallback seed: %s", m.get("model_uid"), seed_err)
    return count
