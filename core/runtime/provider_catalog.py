PROVIDER_MAP: Dict[str, Dict[str, Any]] = {p["provider_id"]: p for p in PROVIDER_DEFINITIONS}


def get_all_provider_definitions() -> List[Dict[str, Any]]:
    """Returns definitions of all registered providers."""
    return list(PROVIDER_DEFINITIONS)


def get_provider_definition(provider_id: str) -> Optional[Dict[str, Any]]:
    """Returns single provider definition or None."""
    return PROVIDER_MAP.get(provider_id.lower().strip())


def get_dpapi_vault_key(provider_id: str) -> str:
    """Returns canonical DPAPI vault key for a provider."""
    return f"PROVIDER_KEY_{provider_id.upper()}"


def seed_default_providers(store: Any) -> int:
    """Seeds default providers into SQLite WAL provider_configs table idempotently."""
    count = 0
    try:
        conn = store._get_connection()
        existing_pids = {row["provider_id"] for row in conn.execute("SELECT provider_id FROM provider_configs;").fetchall()}
        for p in PROVIDER_DEFINITIONS:
            if p["provider_id"] not in existing_pids:
                store.save_provider(p)
                count += 1
        conn.commit()
    except Exception as exc:
        logger.debug("Provider bulk seeding notice: %s", exc)
        for p in PROVIDER_DEFINITIONS:
            try:
                existing = store.get_provider(p["provider_id"])
                if not existing:
                    store.save_provider(p)
                    count += 1
            except Exception as single_err:
                logger.debug("Provider fallback insert skip for '%s': %s", p.get("provider_id"), single_err)
    return count
